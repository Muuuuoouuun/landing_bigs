"""The v8 houses: one 4K sheet per set plus two edits of it (windows lit, clay massing model), cut into matching
sprites so a house can rise as a clay block, be painted with its texture and then light its windows.

  python3 render/variants.py   → src/assets/gen/houses8_<set>_<n>.webp, …_clay, …_lit, …_glow (+ sprites.json)

The objects are found on the base image and the same boxes are cut from every variant (the edits keep the layout;
measured overlap > 99%), each variant keeping its own matte. The clay renders come back faintly pink from the magenta
backdrop, so they are pulled to a warm white.
"""
import json, os
import numpy as np
from PIL import Image
from scipy import ndimage
from key import matte, split

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, 'src', 'assets', 'gen', 'raw')
OUT = os.path.join(ROOT, 'src', 'assets', 'gen')
MAXS = 1200


def clayify(rgb):
    g = rgb @ np.array([0.3, 0.59, 0.11], np.float32)
    g = 40 + g * 0.9
    warm = np.stack([g * 1.02, g * 0.985, g * 0.94], -1)
    return np.clip(warm * 0.88 + rgb * 0.12, 0, 255)


def main():
    meta = {k: v for k, v in json.load(open(os.path.join(OUT, 'sprites.json'))).items() if not k.startswith('houses8_')}
    for sid in ('houses8_a', 'houses8_b', 'houses8_c'):
        base = matte(os.path.join(RAW, f'{sid}.jpg'))
        parts = split(base)
        var = {'': base, '_lit': matte(os.path.join(RAW, f'{sid}_lit.jpg')), '_clay': matte(os.path.join(RAW, f'{sid}_clay.jpg'))}
        for n, (y0, y1, x0, x1, m) in enumerate(parts):
            keep = ndimage.binary_dilation(m, iterations=10)
            for suf, rgba in var.items():
                crop = rgba[y0:y1, x0:x1].astype(np.float32)
                crop[..., 3] *= keep
                if suf == '_clay':
                    crop[..., :3] = clayify(crop[..., :3])
                img = Image.fromarray(crop.astype(np.uint8), 'RGBA')
                s = min(1.0, MAXS / max(img.size))
                if s < 1:
                    img = img.resize((round(img.size[0] * s), round(img.size[1] * s)), Image.LANCZOS)
                name = f'{sid}_{n}{suf}.webp'
                img.save(os.path.join(OUT, name), quality=90, method=6)
                if not suf:
                    meta[name] = {'w': img.size[0], 'h': img.size[1]}
                    size = img.size
            # the windows' bloom: what the lit edit added over the base, softened (screen-blended over the house)
            b = var[''][y0:y1, x0:x1, :3].astype(np.float32)
            l = var['_lit'][y0:y1, x0:x1, :3].astype(np.float32)
            add = np.clip(l - b, 0, 255) * keep[..., None]
            lum = add.max(axis=2)
            core = np.where(lum > 28, 1.0, 0.0)
            soft = ndimage.gaussian_filter(core, 14) * 2.2 + ndimage.gaussian_filter(core, 4) * 0.8
            a = np.clip(soft, 0, 1)
            glow = np.dstack([np.full_like(a, 255), np.full_like(a, 196), np.full_like(a, 110), a * 255]).astype(np.uint8)
            Image.fromarray(glow, 'RGBA').resize(size, Image.LANCZOS).save(os.path.join(OUT, f'{sid}_{n}_glow.webp'), quality=85, method=6)
        print(f'{sid}: {len(parts)} houses × 3 looks')
    json.dump(meta, open(os.path.join(OUT, 'sprites.json'), 'w'), indent=1)
    js = '// generated by render/key.py / variants.py — sprite sizes\nexport default ' + json.dumps(meta, separators=(',', ':')) + ';\n'
    open(os.path.join(OUT, 'sprites.js'), 'w').write(js)


if __name__ == '__main__':
    main()
