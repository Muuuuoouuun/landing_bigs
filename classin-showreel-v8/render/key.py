"""Cut out generated props: key the flat magenta background, despill, split a sheet into separate sprites.

  python3 render/key.py houses_a houses_b ...     # → src/assets/gen/<id>_<n>.png (RGBA, trimmed)

The background colour is sampled from the image corners (generators never hit #FF00FF exactly), the matte is a
soft distance key in RGB with a little erosion + feather, and magenta spill on the edges is pulled back to neutral.
"""
import os, sys, json
import numpy as np
from PIL import Image, ImageFilter
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, 'src', 'assets', 'gen', 'raw')
OUT = os.path.join(ROOT, 'src', 'assets', 'gen')


def key(path, min_area=0.004):
    im = Image.open(path).convert('RGB')
    a = np.asarray(im).astype(np.float32)
    H, W, _ = a.shape
    c = 24
    corners = np.concatenate([a[:c, :c].reshape(-1, 3), a[:c, -c:].reshape(-1, 3), a[-c:, :c].reshape(-1, 3), a[-c:, -c:].reshape(-1, 3)])
    bg = np.median(corners, axis=0)
    d = np.sqrt(((a - bg) ** 2).sum(axis=2))
    # how "magenta" a pixel is: R and B high relative to G
    mag = np.clip(((a[..., 0] + a[..., 2]) / 2 - a[..., 1]) / max(1.0, (bg[0] + bg[2]) / 2 - bg[1]), 0, 1)
    alpha = np.clip((d - 38) / 70, 0, 1)
    alpha = np.where(mag > 0.92, np.minimum(alpha, (1 - mag) * 12), alpha)
    # clean the matte: fill holes inside objects, drop specks, soften the edge by ~1px
    solid = alpha > 0.5
    solid = ndimage.binary_opening(solid, iterations=2)
    filled = ndimage.binary_fill_holes(solid)
    alpha = np.where(filled & ~solid, np.maximum(alpha, 0.0), alpha) * ndimage.binary_dilation(filled, iterations=2)
    am = Image.fromarray((alpha * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.8))
    alpha = np.asarray(am).astype(np.float32) / 255
    # despill: where magenta leaks into the edge, pull R and B down towards G
    spill = np.clip(np.minimum(a[..., 0], a[..., 2]) - a[..., 1], 0, None) * (1 - alpha) * 1.0 + np.clip(np.minimum(a[..., 0], a[..., 2]) - a[..., 1] - 18, 0, None) * alpha * 0.6
    out = a.copy()
    out[..., 0] -= spill
    out[..., 2] -= spill
    rgba = np.dstack([np.clip(out, 0, 255), alpha * 255]).astype(np.uint8)
    # split into connected objects
    lab, n = ndimage.label(ndimage.binary_dilation(alpha > 0.3, iterations=6))
    parts = []
    for i in range(1, n + 1):
        ys, xs = np.where(lab == i)
        if len(ys) < min_area * H * W:
            continue
        y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
        m = (lab[y0:y1, x0:x1] == i)
        crop = rgba[y0:y1, x0:x1].copy()
        crop[..., 3] = (crop[..., 3] * m).astype(np.uint8)
        parts.append(((y0 + y1) / 2, (x0 + x1) / 2, crop))
    # reading order: rows top→bottom, then left→right
    parts.sort(key=lambda p: (round(p[0] / (H / 3)), p[1]))
    return [p[2] for p in parts]


def main():
    meta = {}
    mp = os.path.join(OUT, 'sprites.json')
    if os.path.exists(mp):
        meta = json.load(open(mp))
    for aid in sys.argv[1:]:
        src = next((os.path.join(RAW, f'{aid}.{e}') for e in ('png', 'jpg') if os.path.exists(os.path.join(RAW, f'{aid}.{e}'))), None)
        if not src:
            print(f'{aid}: missing'); continue
        parts = key(src)
        for k, crop in enumerate(parts):
            img = Image.fromarray(crop, 'RGBA')
            # keep sprites a sensible size for the browser
            s = min(1.0, 900 / max(img.size))
            if s < 1:
                img = img.resize((round(img.size[0] * s), round(img.size[1] * s)), Image.LANCZOS)
            name = f'{aid}_{k}.png'
            img.save(os.path.join(OUT, name), optimize=True)
            meta[name] = {'w': img.size[0], 'h': img.size[1]}
        print(f'{aid}: {len(parts)} sprites')
    json.dump(meta, open(mp, 'w'), indent=1)
    with open(os.path.join(OUT, 'sprites.js'), 'w') as f:  # the same table as an ES module for the film
        f.write('// Generated by render/key.py — sprite sizes (px) of the cut-out generated props.\nexport default ' + json.dumps(meta) + ';\n')


if __name__ == '__main__':
    main()
