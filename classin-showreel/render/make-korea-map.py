"""One-off tool: rasterises South Korea's province outlines into a dot-matrix map
and projects the branch-network nodes into the same coordinate space.

Source data: southkorea/southkorea-maps (KOSTAT 2013, simplified provinces GeoJSON).
Usage: python3 render/make-korea-map.py skorea_provinces_geo_simple.json src/assets/korea-map.js
"""
import json, math, random, sys
from PIL import Image, ImageDraw

src, out = sys.argv[1], sys.argv[2]
LON0, LON1, LAT0, LAT1 = 125.6, 130.0, 33.0, 38.7
KX = math.cos(math.radians(36))           # equirectangular, corrected at mid-latitude
W = 1000                                    # map plane width (units = px in the film)
SCALE = W / ((LON1 - LON0) * KX)
H = round((LAT1 - LAT0) * SCALE)

def proj(lon, lat):
    return ((lon - LON0) * KX * SCALE, (LAT1 - lat) * SCALE)

SS = 4  # supersample the mask
mask = Image.new('L', (W * SS, H * SS), 0)
dr = ImageDraw.Draw(mask)
for f in json.load(open(src, encoding='utf-8'))['features']:
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    for poly in polys:
        for k, ring in enumerate(poly):
            pts = [tuple(c * SS for c in proj(lon, lat)) for lon, lat in ring]
            if len(pts) > 2:
                dr.polygon(pts, fill=255 if k == 0 else 0)

STEP = 11  # dot pitch in map units
dots = []
for y in range(STEP // 2, H, STEP):
    for x in range(STEP // 2, W, STEP):
        # dilate slightly so thin coastlines/islands still get a dot
        hit = any(mask.getpixel((min(W * SS - 1, max(0, (x + dx) * SS)), min(H * SS - 1, max(0, (y + dy) * SS)))) > 0
                  for dx in (-2, 0, 2) for dy in (-2, 0, 2))
        if hit:
            dots.append((x, y))

CITIES = [  # (label, lon, lat, tier) — tier 0 = HQ, 1 = labelled branch, 2 = unlabelled branch
    ('서울 본사', 127.06, 37.50, 0), ('인천 송도', 126.65, 37.39, 1), ('일산', 126.77, 37.66, 2),
    ('분당 정자', 127.12, 37.36, 1), ('수원', 127.03, 37.27, 2), ('춘천', 127.73, 37.88, 2),
    ('강릉', 128.90, 37.75, 1), ('원주', 127.92, 37.34, 2), ('청주', 127.49, 36.64, 2),
    ('천안', 127.15, 36.82, 2), ('세종', 127.29, 36.48, 2), ('대전 둔산', 127.38, 36.35, 1),
    ('안동', 128.73, 36.57, 2), ('포항', 129.36, 36.02, 2), ('전주', 127.15, 35.82, 2),
    ('대구 수성', 128.63, 35.86, 1), ('광주 봉선', 126.91, 35.13, 1), ('울산', 129.31, 35.54, 2),
    ('창원', 128.68, 35.23, 2), ('김해', 128.88, 35.23, 2), ('부산 센텀', 129.13, 35.17, 1),
    ('목포', 126.39, 34.81, 2), ('여수', 127.66, 34.76, 2), ('제주', 126.53, 33.50, 1),
]
nodes = [{'label': l, 'x': round(proj(lo, la)[0], 1), 'y': round(proj(lo, la)[1], 1), 'tier': t} for l, lo, la, t in CITIES]

# extra unlabelled branches scattered on land, biased toward the dense north-west (capital area)
rnd = random.Random(7)
hq = nodes[0]
pool = [d for d in dots if all((d[0] - n['x']) ** 2 + (d[1] - n['y']) ** 2 > 30 ** 2 for n in nodes)]
extra = []
while len(extra) < 40 and pool:
    d = rnd.choice(pool)
    dist = math.hypot(d[0] - hq['x'], d[1] - hq['y'])
    if rnd.random() < 0.35 + 0.65 * math.exp(-dist / 260) and all(math.hypot(d[0] - e[0], d[1] - e[1]) > 26 for e in extra):
        extra.append(d)
nodes += [{'label': '', 'x': x, 'y': y, 'tier': 3} for x, y in extra]

with open(out, 'w', encoding='utf-8') as fh:
    fh.write('// Generated by render/make-korea-map.py (KOSTAT 2013 outlines via southkorea/southkorea-maps) — do not edit by hand.\n')
    fh.write(f'export const MAP_W = {W};\nexport const MAP_H = {H};\nexport const DOT_STEP = {STEP};\n')
    fh.write('export const DOTS = ' + json.dumps([v for d in dots for v in d], separators=(',', ':')) + ';\n')
    fh.write('export const NODES = ' + json.dumps(nodes, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('map', W, 'x', H, 'dots', len(dots), 'nodes', len(nodes))
