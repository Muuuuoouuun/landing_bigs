// One-off tool: vectorises the official ClassIn wordmark into per-glyph SVG paths
// so the film can animate each glyph (the slanted i-dot is the hero of the edit).
//
// Input must be a flattened black-on-white PNG (alpha removed), e.g. made with:
//   python3 -c "from PIL import Image; im=Image.open('logo.png').convert('RGBA'); \
//     bg=Image.new('RGBA',im.size,'white'); bg.alpha_composite(im); \
//     bg.convert('L').point(lambda v:0 if v<200 else 255).resize((2720,357*2)).save('logo_bw.png')"
// Usage: node render/trace-logo.mjs logo_bw.png src/assets/logo-paths.js
import potrace from 'potrace';
import fs from 'fs';

const [src, out] = process.argv.slice(2);

potrace.trace(src, { threshold: 128, turdSize: 20 }, (err, svg) => {
  if (err) throw err;
  const d = svg.match(/\sd="([^"]+)"/)[1];
  const [, , w, h] = svg.match(/viewBox="([^"]+)"/)[1].split(' ').map(Number);
  const subs = d.split(/(?=M)/).map(s => s.trim()).filter(Boolean).map(s => {
    const n = s.match(/-?\d+(\.\d+)?/g).map(Number);
    const xs = n.filter((_, i) => i % 2 === 0), ys = n.filter((_, i) => i % 2 === 1);
    // round coordinates to 1 decimal to keep the module small
    return { d: s.replace(/-?\d+\.\d+/g, v => (+v).toFixed(1)), x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) };
  });
  // glyph order by x; holes (fully contained subpaths) merge into their parent
  const glyphs = [];
  subs.sort((a, b) => a.x0 - b.x0 || a.y0 - b.y0).forEach(s => {
    const parent = glyphs.find(g => s.x0 > g.x0 && s.x1 < g.x1 && s.y0 > g.y0 && s.y1 < g.y1);
    if (parent) parent.d += ' ' + s.d; else glyphs.push({ ...s });
  });
  const names = ['C', 'l', 'a', 's1', 's2', 'iDot', 'iStem', 'n'];
  glyphs.sort((a, b) => a.x0 - b.x0 || a.y0 - b.y0);
  if (glyphs.length !== names.length) throw new Error(`expected ${names.length} glyphs, got ${glyphs.length}`);
  const body = glyphs.map((g, i) => `  ${names[i]}: { d: '${g.d}', box: [${[g.x0, g.y0, g.x1, g.y1].map(v => Math.round(v)).join(', ')}] },`).join('\n');
  fs.writeFileSync(out, `// Generated by render/trace-logo.mjs from public/image/ClassIn logo-1.png — do not edit by hand.\nexport const LOGO_W = ${w};\nexport const LOGO_H = ${h};\nexport const LOGO_GREEN = '#04BC09';\nexport const GLYPHS = {\n${body}\n};\n`);
  console.log('wrote', out, glyphs.map((g, i) => names[i] + '@' + Math.round(g.x0)).join(' '));
});
